# Data       <-  Data.0
# Data       <-  Data.1

F.Part.1     <-  function(Data){

  Split      <-  strsplit(Data, "\\s+")
  Checksum   <-  0

  for (i in seq_along(Split)) {
    Row        <-  as.numeric(Split[[i]])
    Checksum   <-  Checksum + max(Row) - min(Row)
  }

  return(Checksum)
}

#====================================================================================================#
# Execution
#====================================================================================================#


F.Part.1   <-  function(Data){
  
  Year     <-  2020
  
  X        <-  as.numeric(Data)

  Delta    <-  Year - X 
  
  Which    <-  which(Delta %in% X)
  
  Product  <-  prod(X[Which])
  
  return(Product)
  
}



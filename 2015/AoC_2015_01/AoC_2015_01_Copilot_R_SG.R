# Data       <-  Data.0
# Data       <-  Data.1

F.Part.1     <-  function(Data){

  CharVal    <-  c("(" = 1,
                   ")" = -1)

  Split      <-  strsplit(Data, "")[[1]]

  Value      <-  CharVal[Split]

  Floor      <-  sum(Value)

  return(Floor)
}

#====================================================================================================#
# Execution
#====================================================================================================#


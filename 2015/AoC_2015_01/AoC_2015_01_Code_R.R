F.Part.2         <-  function(Data){
  
  CharVal        <-  c("(" = 1, 
                       ")" = -1)
   
  Split          <-  strsplit(Data, "")[[1]]
  
  Value          <-  CharVal[Split]
  
  Position       <-  cumsum(Value)
  
  FirstBasement  <-  which(Position == -1)[[1]]        
  
  return(FirstBasement)
  
}


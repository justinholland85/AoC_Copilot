F.Part.2    <-  function(Data){
  
  Split     <-  strsplit(Data, "")
  Move      <-  lapply(Split, match, c("U", "R", "D", "L"))
  
  
  
  #--------------------------------------------------------------------------------------------------#
  # Define keypad
  #--------------------------------------------------------------------------------------------------#
  
  KeyPad   <-  do.call(rbind, list(c("x", "x", 1, "x", "x"), 
                                   c("x", 2, 3, 4, "x"), 
                                   c(5, 6, 7, 8, 9), 
                                   c("x", "A", "B", "C", "x"), 
                                   c("x", "x", "D", "x", "x" )))
  
  Origin <- c(-2,0)
  
  #--------------------------------------------------------------------------------------------------#
  # Key Function
  #--------------------------------------------------------------------------------------------------#
  
  F.Key   <-  function(X){
    
    x   <-  3 + X[[1]]
    y   <-  3 - X[[2]]
    
    Key <- KeyPad[y, x]
    
    return(Key)
    
  }
  
  
  #--------------------------------------------------------------------------------------------------#
  # Movement function
  #--------------------------------------------------------------------------------------------------#


  F.Move    <-  function(X, Start = c(-2,0)){
    
    Vectors       <-  list(c(0, 1), 
                           c(1, 0), 
                           c(0, -1), 
                           c(-1, 0))
    
    Move.Vectors  <-  Vectors[X]
    
    N.X           <-  length(X)
    
    Pos   <-  list(Start)
    
    for(i in 1:N.X){
      
      Test.Pos    <-  pmax(pmin(Pos[[i]] + Move.Vectors[[i]], 2), -2)
      Test.Key    <-  F.Key(Test.Pos)
      
      if(Test.Key == "x"){Pos[[i+1]]  <- Pos[[i]]} else {Pos[[i+1]]  <- Test.Pos}
      
    }
    
    return(Pos[[N.X+1]])
    
  }

  
  #--------------------------------------------------------------------------------------------------#
  # Apply Movements
  #--------------------------------------------------------------------------------------------------#
  
  N.Move   <-  length(Move)
  
  EndPoints  <-  list()
  
  for(i in 1:N.Move){
    
    if(i == 1){Start <- Origin} else {Start <- EndPoints[[i-1]] }
    
    EndPoints[[i]]  <-  F.Move(Move[[i]], Start)
    
  }
  
  #--------------------------------------------------------------------------------------------------#
  # Keys
  #--------------------------------------------------------------------------------------------------#
  
  Keys   <- unlist(lapply(EndPoints, F.Key))
  
  BathroomCode   <-  paste(Keys, collapse = "")
  
  return(BathroomCode)
  

}



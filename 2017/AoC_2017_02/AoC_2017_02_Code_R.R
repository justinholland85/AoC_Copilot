F.Part.1    <-  function(Data){
  
  Split        <-  strsplit(Data, "\t")
  Spreadsheet  <-  lapply(Split, as.numeric)
  
  Min          <-  unlist(lapply(Spreadsheet, min))
  Max          <-  unlist(lapply(Spreadsheet, max))
  
  Delta        <-  Max - Min
  
  Checksum     <-  sum(Delta)
  
  return(Checksum)
  
  
}

#====================================================================================================#
# Execution  
#====================================================================================================#

F.Part.1    <-  function(Data, Set.Pos.1 = 12, Set.Pos.2 = 2, Test = 0 ){
  
  Base       <-  as.numeric(strsplit(Data, ",")[[1]])
 
  X          <-  Base

  if(Test == 0){ 
  X[2]       <-  Set.Pos.1
  X[3]       <-  Set.Pos.2
  }
  
  #==================================================================================================#
  # Basic processing function
  #==================================================================================================#
  
  F.Process.Quad   <-  function(X,p.0){
    
    # Positions references start at zero so need to shift one to the right
    
    p.1  <- X[p.0+1] + 1
    p.2  <- X[p.0+2] + 1
    p.3  <- X[p.0+3] + 1  
    
    x.0  <- X[p.0]
    x.1  <- X[p.1]
    x.2  <- X[p.2]

    if(x.0 == 99){Terminate <- 1 } else {Terminate <- 0}
    if(x.0 == 1 ){Val <- x.1 + x.2}
    if(x.0 == 2 ){Val <- x.1 * x.2} 
    if(x.0 %in% c(1,2,99)){Error <- 0} else {Error <- 1}
    
    if(x.0 %in% c(1,2)){X[p.3] <- Val}
    
    return(list("X"         = X, 
                "Terminate" = Terminate, 
                "Error"     = Error  ))
    
  }

  
  #==================================================================================================#
  # Main loop
  #==================================================================================================#
  
  List.X   <-  list(X)
  p.0      <-  1
  
  Counter  <-  2
  
  repeat{
    
    Adjust  <-  F.Process.Quad(X, p.0)
    
    if(Adjust$Terminate == 1 | Adjust$Error == 1){break}
    
    X                  <-  Adjust$X
     
    List.X[[Counter]]  <-  X
    
    p.0                <-  p.0 + 4
    Counter            <-  Counter + 1
    
    
  }
  
   V.0  <-  X[[1]]
   
   return(V.0)
  
}


#====================================================================================================#
# Execution  
#====================================================================================================#
F.Part.1(Data.0, Test = 1)


F.Part.1(Data.1)




F.Part.2   <-  function(Data){
  
  DF            <-  data.frame(do.call(rbind, strsplit(Data, "  ")))
  DF            <-  lapply(DF, as.numeric)
  
  Table.X2      <-  table(DF$X2)
  
  Multiplier    <-  Lib.NA.To.Zero(as.numeric(Table.X2[match(DF$X1, Lib.NumericNames(Table.X2))]))
  
  Similarity    <-  sum(DF$X1 * Multiplier)
  
  return(Similarity)
  
  
}



F.Part.1    <-  function(Data){
  
  Split     <-  strsplit(Data, "")
  Move      <-  lapply(Split, match, c("U", "R", "D", "L"))
  
  Origin <- c(0,0)
  
  #--------------------------------------------------------------------------------------------------#
  # Movement function
  #--------------------------------------------------------------------------------------------------#

  F.Move    <-  function(X, Start = c(0,0)){
  
    Vectors   <-  list(c(0, 1), 
                       c(1, 0), 
                       c(0, -1), 
                       c(-1, 0))
    
    Move.Vectors  <-  Vectors[X]
    
    N.X       <-  length(X)
    
    Pos   <-  list(Start)
    
    for(i in 1:N.X){
      
      Pos[[i+1]]  <-   pmax(pmin(Pos[[i]] + Move.Vectors[[i]], 1), -1)
      
    }
    
    return(Pos[[N.X+1]])
    
  
  }
  
  #--------------------------------------------------------------------------------------------------#
  # Key Function
  #--------------------------------------------------------------------------------------------------#

  F.Key   <-  function(X){
    
    Key <- 2 + X[[1]] + 3 * (1 - X[[2]])
    
    return(Key)
    
  }
  
  
  #--------------------------------------------------------------------------------------------------#
  # Apply Movements
  #--------------------------------------------------------------------------------------------------#
  
  N.Move   <-  length(Move)
  
  EndPoints  <-  list()
  
  for(i in 1:N.Move){
    
   if(i == 1){Start <- Origin} else {Start <- EndPoints[[i-1]] }
    
    EndPoints[[i]]  <-  F.Move(Move[[i]], Start)
    
  }
  
  
  #--------------------------------------------------------------------------------------------------#
  # Keys
  #--------------------------------------------------------------------------------------------------#
  
  Keys   <- unlist(lapply(EndPoints, F.Key))
  
  BathroomCode   <-  as.numeric(paste(Keys, collapse = ""))
  
  return(BathroomCode)
  
}


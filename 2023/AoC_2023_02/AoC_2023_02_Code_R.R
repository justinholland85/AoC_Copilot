F.Part.2          <-  function(Data){
  
  Games       <-  lapply(strsplit(Data, ":"), Lib.Take.One, 2)

  Max         <-  c("blue" = 14, "green" = 13, "red" = 12)
  
  #==================================================================================================#
  # F.Game.Power
  #==================================================================================================#
  
  F.Game.Power    <- function(Game){
    
    
    Pull      <-  strsplit(trimws(Game), ";")[[1]]
    Groups    <-  unlist(strsplit(Pull, ","))
    
    Counts    <-  strsplit(trimws(Groups), " ") 
    Counts    <-  data.frame("Colour" = unlist(lapply(Counts, Lib.Take.One, 2)), 
                             "N"      = as.numeric(unlist(lapply(Counts, Lib.Take.One, 1))))
    
    Largest   <-  Lib.MapVecToSet(tapply(Counts$N, Counts$Colour, max), names(Max)) 

    return(prod(Largest))
  }
  
  #==================================================================================================#
  # Calcs
  #==================================================================================================#
  
  
  Games.Power     <- unlist(lapply(Games, F.Game.Power))
  
  Power.Tot       <-  sum(Games.Power)
  
  return(Power.Tot)
  
}


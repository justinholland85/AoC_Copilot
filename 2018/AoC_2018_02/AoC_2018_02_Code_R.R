F.Part.1    <-  function(Data){
  
  Split             <-  strsplit(Data, "")
  LetterCounts      <-  lapply(Split, table)
  CountCounts       <-  lapply(LetterCounts, table)  
  CountVals         <-  lapply(CountCounts, Lib.NumericNames)  
  
  Has.2             <-  unlist(lapply(CountVals, Lib.B.in.A, "2"))
  Has.3             <-  unlist(lapply(CountVals, Lib.B.in.A, "3"))
  
  CheckSum          <-  sum(Has.2) * sum(Has.3)
  
  return(CheckSum)
  
}

#====================================================================================================#
# Execution  
#====================================================================================================#
F.Part.1(Data.0.p1)
F.Part.1(Data.1)



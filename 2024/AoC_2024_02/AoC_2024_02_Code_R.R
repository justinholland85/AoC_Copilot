F.Part.2    <-  function(Data){
  
  Reports   <-  lapply(strsplit(Data," "), as.numeric)
  
  
  #==================================================================================================#
  # F.Report.Safe
  #==================================================================================================#
  
  F.Report.Safe  <-  function(Report){
    
    Length        <-  length(Report)
    Delta         <-  Report[-1] - Report[-Length]
    
    
    Test.Sign     <-  length(unique(sign(Delta))) == 1
    
    Test.Diff     <-  prod(abs(Delta) %in% seq(1,3))
    
    Safe          <-  Test.Sign * Test.Diff
    
    return(Safe)
    
  }
  
  #==================================================================================================#
  # F.Dampener.Safe
  #==================================================================================================#
  
  F.Dampener.Safe  <-  function(Report){
    
    Length        <-  length(Report)
    
    Safe  <-  0
    
    for(i in 1:Length){
      
      Safe   <-  F.Report.Safe(Report[-i])
      if(Safe == 1){break}
    }
    
    return(Safe)
    
  }
  
  
  #==================================================================================================#
  # Safety Checks
  #==================================================================================================#
  
  Safe.Original  <-  unlist(lapply(Reports, F.Report.Safe))
  Safe.Dampener  <-  unlist(lapply(Reports, F.Dampener.Safe))
  
  Reports.Safe   <- Safe.Original | Safe.Dampener
  
  Safe.Count     <-  sum(Reports.Safe)
  
  return(Safe.Count)
  
}


#====================================================================================================#
# Execution  
#====================================================================================================#
F.Part.2(Data.0)
F.Part.2(Data.1)



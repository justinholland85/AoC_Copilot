F.Part.1   <-  function(Data){
  
  Depth       <-  as.numeric(Data)
  Depth.Prev  <-  c(Inf, Depth[-length(Depth)])  
  
  Increased   <-  sum(Depth > Depth.Prev)
  
  return(Increased)
  
}



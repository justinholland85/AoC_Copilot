F.Part.2     <-  function(Data){

  Keypad     <-  matrix(c(NA, NA, "1", NA, NA,
                          NA, "2", "3", "4", NA,
                          "5", "6", "7", "8", "9",
                          NA, "A", "B", "C", NA,
                          NA, NA, "D", NA, NA),
                        nrow = 5, byrow = TRUE)
  Position   <-  c(3, 1)
  Code       <-  character()
  Split      <-  strsplit(Data, "")

  for (i in seq_along(Split)) {
    for (Move in Split[[i]]) {
      if (Move == "U") {
        Next     <-  Position + c(-1, 0)
      } else if (Move == "D") {
        Next     <-  Position + c(1, 0)
      } else if (Move == "L") {
        Next     <-  Position + c(0, -1)
      } else if (Move == "R") {
        Next     <-  Position + c(0, 1)
      }

      if (all(Next >= 1 & Next <= 5) &&
          !is.na(Keypad[Next[1], Next[2]])) {
        Position <-  Next
      }
    }

    Code       <-  c(Code, Keypad[Position[1], Position[2]])
  }

  return(paste0(Code, collapse = ""))
}


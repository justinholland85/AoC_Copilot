F.Part.2     <-  function(Data){

  Split      <-  strsplit(Data, "\\s+")
  Checksum   <-  0

  for (i in seq_along(Split)) {
    Row        <-  as.numeric(Split[[i]])
    Pairs      <-  combn(Row, 2)
    Divisible  <-  Pairs[, pmax(Pairs[1, ], Pairs[2, ]) %%
                           pmin(Pairs[1, ], Pairs[2, ]) == 0,
                         drop = FALSE]
    Checksum   <-  Checksum + sum(pmax(Divisible[1, ], Divisible[2, ]) /
                                    pmin(Divisible[1, ], Divisible[2, ]))
  }

  return(Checksum)
}

#====================================================================================================#
# Execution
#====================================================================================================#

F.Part.2(Data.0b)
F.Part.2(Data.1)

F.Part.2   <-  function(Data){
  
  Mass.0   <-  as.numeric(Data)
  
  Fuel     <-  list()    
  
  i.Mass   <-  Mass.0  
  
  i        <- 1
  
  repeat{
    
    Fuel[[i]]  <-   pmax(floor(i.Mass / 3) - 2, 0) 
    
    if(sum(Fuel[[i]]) == 0){break} else {i.Mass <- Fuel[[i]]}
    
    i         <-  i + 1
    
    print(i)
    
  }
  
  
  Fuel.Tot  <-  sum(unlist(Fuel))
  
  return(Fuel.Tot)
  
}


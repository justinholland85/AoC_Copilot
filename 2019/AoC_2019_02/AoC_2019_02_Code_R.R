F.Part.2    <-  function(Data){
  
  Grid     <-  expand.grid(Noun = seq(0,99), Verb = seq(0, 99))
  Target   <-  19690720
  
  
  for(i in 1:nrow(Grid)){
    
  Test  <-  F.Part.1(Data, Set.Pos.1 = Grid$Noun[i], Set.Pos.2 = Grid$Verb[i])
  
  if(Test == Target){break}
  
  if(i %% 1000 == 0){print(i)}
  
  }
  
  Noun  <-  Grid$Noun[i]
  Verb  <-  Grid$Verb[i]
  
  Noun.Verb   <-  100 * Noun + Verb
  
  return(Noun.Verb)
  
  
}


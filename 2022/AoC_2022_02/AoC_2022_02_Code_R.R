# Note: a paper scissors rock game is a win if Play - Opponent is equal to 1 modulo 3
# A    <-  c(1,2,3)
# B    <-  c(3,1,2)
# (A - B) %% 3
# (B - A) %% 3 


Data   <-  Data.0

F.Part.1          <-  function(Data){
  
  Split              <-  data.frame(do.call(rbind, strsplit(Data, " ")))
  colnames(Split)    <-  c("Opp", "Play")
  
  
  Game     <-  data.frame("Opp" = match(Split$Opp, LETTERS[1:3]), 
                          "Play" = match(Split$Play, LETTERS[24:26])
                          )
 
  
  Game$Result   <- c(3,6,0)[(Game$Play - Game$Opp) %% 3 + 1]
  Game$Score    <- Game$Result + Game$Play
  
  Score.Tot     <-  sum(Game$Score)
  
  return(Score.Tot)
  
}

#====================================================================================================#
# Execution  
#====================================================================================================#
F.Part.1(Data.0)
F.Part.1(Data.1)



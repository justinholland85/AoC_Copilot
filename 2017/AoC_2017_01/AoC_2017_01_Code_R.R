F.Part.1   <-  function(Data){
  
  Split     <-  as.numeric(strsplit(Data, "")[[1]])
  
  X.0       <-  Split
  X.1       <-  c(Split[-1], Split[1])
  
  Same      <-  X.0 == X.1
  
  Captcha   <-  sum(Same * X.0) 
  
  return(Captcha)
  
}


Data   <-  Data.0

F.Part.2          <-  function(Data){
  
  Split              <-  data.frame(do.call(rbind, strsplit(Data, " ")))
  colnames(Split)    <-  c("Opp", "Strat")
  
  
  Game               <-  data.frame("Opp" = match(Split$Opp, LETTERS[1:3]), 
                                    "Strat" = match(Split$Strat, LETTERS[24:26]))
  

  Game$Target.Mod3   <-  c(2,0,1)[Game$Strat]
  
  Game$Play          <-  (Game$Target.Mod3 + Game$Opp)  %% 3 
  Game$Play          <-  ifelse(Game$Play == 0, 3, Game$Play )
  
  Game$Result        <-  c(0,3,6)[Game$Strat]
  
  Game$Score         <-  Game$Result + Game$Play
  
  Score.Tot          <-  sum(Game$Score)
  
  return(Score.Tot)
  
}

#====================================================================================================#
# Execution  
#====================================================================================================#
F.Part.2(Data.0)

F.Part.2(Data.1)






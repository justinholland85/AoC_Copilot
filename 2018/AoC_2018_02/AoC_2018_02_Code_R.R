F.Part.2    <-  function(Data){
  
  Grid       <-  expand.grid("x" = Data, "y" = Data, stringsAsFactors = FALSE )
  Nchar      <-  nchar(Data[[1]])
  
  
  F.Same <-  function(x,y){
    
    X   <-  strsplit(x, "")[[1]]
    Y   <-  strsplit(y, "")[[1]]
    
    return(X[X == Y])
  }
  
  Same       <-  mapply(F.Same, as.list(Grid$x), as.list(Grid$y), SIMPLIFY = FALSE)
  
  Count.Same <-  unlist(lapply(Same, length))
  
  Box        <-  which(Count.Same == (Nchar - 1))[[1]]
  
  ID         <-  paste(Same[Box][[1]], collapse = "")
  
  return(ID)
  
}

#====================================================================================================#
# Execution  
#====================================================================================================#
F.Part.2(Data.0.p2)
F.Part.2(Data.1)






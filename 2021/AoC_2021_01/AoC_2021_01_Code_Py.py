def F_Part_2(Data): 

    N             = len(Data)  

    Depth         = Data
    Depth_Lag_1   = np.concatenate(([np.inf], Depth[0:(N-1)]))
    Depth_Lag_2   = np.concatenate(([np.inf], [np.inf], Depth[0:(N-2)]))

    Groups        = [Depth, Depth_Lag_1, Depth_Lag_2]
    
    Group_Sums    =  np.sum(Groups, axis=0)
    
    Increased     = F_Part_1(Group_Sums)


    return(Increased)




F.Part.2   <-  function(Data){
  
  Calories      <-  as.numeric(Data)
  
  Elf.ID        <-  cumsum(is.na(Calories))
  
  Elf.Calories  <-  tapply(Lib.NA.To.Zero(Calories), Elf.ID, sum)
  
  Sum.Top3      <-  sum(sort(Elf.Calories, decreasing = TRUE)[1:3])
  
  return(Sum.Top3)
  
}


#====================================================================================================#
# Execution  
#====================================================================================================#

F.Part.2(Data.0)
F.Part.2(Data.1)

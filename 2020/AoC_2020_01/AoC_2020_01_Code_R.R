F.Part.2   <-  function(Data){
  
  Year       <-  2020
  
  X          <-  as.numeric(Data)
  
  Delta      <-  Year - X 
  
  Pairs      <-  expand.grid("A" = X, "B" = X)   
  
  Pairs$Sum  <-  rowSums(Pairs)
  
  Which      <-  which(Pairs$Sum %in% Delta)
  
  # Relying here on the three numbers needing to be distinct:
   
  Product    <-  prod(unique(Pairs$A[Which]))
  
  return(Product)
  
}


#====================================================================================================#
# Execution  
#====================================================================================================#

F.Part.2(Data.0)
F.Part.2(Data.1)


F.Part.1   <-  function(Data){

  DF            <-  data.frame(do.call(rbind, strsplit(Data, "  ")))
  DF            <-  lapply(DF, as.numeric)
  
  X1            <-  sort(DF$X1)
  X2            <-  sort(DF$X2)

  Dist          <-  abs(X1 - X2)
  TotDist       <-  sum(Dist) 

return(TotDist)
}




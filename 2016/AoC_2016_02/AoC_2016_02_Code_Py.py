def F_Part_1(Data): 

    Split      = [list(x) for x in Data]

    Direction = {"U": 1, "R": 2, "D": 3, "L": 4}

    Move      = [[Direction[x] for x in Row] for Row in Split]

    Origin    = np.array([0,0])
    
    #--------------------------------------------------------------------------------------------------#
    # Movement function
    #--------------------------------------------------------------------------------------------------#
 
    def F_Move(X, Start = [0,0]):

        Vectors        = np.array([[ 0,  1],
                                   [ 1,  0],
                                   [ 0, -1],
                                   [-1,  0]
                                  ]) 

        Move_Vectors   =  Vectors[np.array(X)-1]

        N_X            = len(X)

        Pos = [np.array(Start)]

        for i in range(N_X):
            Pos.append(np.clip(Pos[i] + Move_Vectors[i], -1, 1))

        return Pos[N_X]

     
    #--------------------------------------------------------------------------------------------------#
    # Key Function
    #--------------------------------------------------------------------------------------------------#

    def F_Key(X):
    
        Key = 2 + X[0] + 3 * (1 - X[1])

        return Key

    #--------------------------------------------------------------------------------------------------#
    # Apply Movements
    #--------------------------------------------------------------------------------------------------#
  
    N_Move    = len(Move)  

    EndPoints = []

    for i in range(N_Move):

        if i == 0 :
            Start = Origin
        else:
            Start = EndPoints[i-1]

        EndPoints.append(F_Move(Move[i], Start))

    #--------------------------------------------------------------------------------------------------#
    # Keys
    #--------------------------------------------------------------------------------------------------#
  
    Keys = np.array([F_Key(x) for x in EndPoints])

    BathroomCode = "".join(map(str, Keys))
  
    return BathroomCode


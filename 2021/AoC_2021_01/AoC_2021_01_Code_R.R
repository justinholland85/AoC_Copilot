F.Part.2   <-  function(Data){
  
  N             <-  length(Data)
  
  Depth        <-  as.numeric(Data)
  Depth.Lag_1  <-  c(NA, Depth[-N])  
  Depth.Lag_2  <-  c(NA, NA, Depth[-c(N, N - 1)])  
  
  GroupSums    <- rowSums(cbind(Depth, 
                                Depth.Lag_1, 
                                Depth.Lag_2))
  
  Increased    <-  F.Part.1(Lib.NA.To.Val(GroupSums, Inf))
  
  return(Increased)
  
}


#====================================================================================================#
# Execution  
#====================================================================================================#

F.Part.2(Data.0)
F.Part.2(Data.1)


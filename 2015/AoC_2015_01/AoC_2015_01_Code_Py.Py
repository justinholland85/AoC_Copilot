def F_Part_2(Data):

    CharVal = {
    "(":  1,
    ")": -1
    }

    Split = list(Data)
    
    Value = [CharVal[x] for x in Split]

    Position = np.cumsum(Value)
   
    FirstBasement = np.where(Position == -1)[0][0]  # very normal
    # FirstBasement = np.flatnonzero(Position == -1)[0] # slightly cleaner
    return FirstBasement


F.Part.2    <-  function(Data){
  
  Split        <-  strsplit(Data, "\t")
  Spreadsheet  <-  lapply(Split, as.numeric)
  

  F.Quotient   <-  function(X){
    
    Grid   <-  expand.grid(x = X, y = X)
    Grid   <-  Grid[Grid$x != Grid$y, ]
    
    Grid$Remainder  <-  Grid$x %% Grid$y
    Grid$Quotient   <-  Grid$x / Grid$y
    
    return(Grid$Quotient[Grid$Remainder == 0])
    
  }
  
  
  Quotient     <-  unlist(lapply(Spreadsheet, F.Quotient))
  
  Checksum     <-  sum(Quotient)
  
  return(Checksum)
  
}

#====================================================================================================#
# Execution  
#====================================================================================================#
F.Part.2(Data.0.p2)

F.Part.2(Data.1)










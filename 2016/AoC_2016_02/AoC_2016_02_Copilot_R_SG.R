F.Part.1     <-  function(Data){

  Keypad     <-  matrix(as.character(1:9), nrow = 3, byrow = TRUE)
  Position   <-  c(2, 2)
  Code       <-  character()
  Split      <-  strsplit(Data, "")

  for (i in seq_along(Split)) {
    for (Move in Split[[i]]) {
      if (Move == "U") {
        Next     <-  Position + c(-1, 0)
      } else if (Move == "D") {
        Next     <-  Position + c(1, 0)
      } else if (Move == "L") {
        Next     <-  Position + c(0, -1)
      } else if (Move == "R") {
        Next     <-  Position + c(0, 1)
      }

      if (all(Next >= 1 & Next <= 3)) {
        Position <-  Next
      }
    }

    Code       <-  c(Code, Keypad[Position[1], Position[2]])
  }

  return(paste0(Code, collapse = ""))
}

#====================================================================================================#
# Execution
#====================================================================================================#

F.Part.1(Data.0)
F.Part.1(Data.1)


